def advice_for(result):
    """Return Bangla advice based on the triage result."""
    if not isinstance(result, dict):
        return ADVICE["UNKNOWN"].copy()

    level = str(result.get("risk_level", "UNKNOWN")).upper()

    return ADVICE.get(level, ADVICE["UNKNOWN"]).copy()
